"""Every number of the manuscript (v0.2) from the FINAL result files: fp32 deterministic inference,
3 Siamese seeds vs 3 paper-model (B1) seeds, paired tests.

Inputs (in ../remote_artifacts/runs):
  <run>/eval_fp32/results.json, <run>/analysis_fp32/{analysis.json,predictions.npz}
  gfsl_fp32/<run>/gfsl_improve.json             rare-class classifier study (30 K-shot draws)
  paired_gfsl_final.json                        paired tests of the classifier study
  paired_seeds_fp32_local.json                  9 Siamese-vs-B1 seed pairs (14-class, 22-class NCM)
  <run>/train_summary.json, report_data.json    training summaries, pilot (F1-F3) results
and ../tem_fewshot/temfs/expected_counts.json for the dataset table.

    python extract_numbers_final.py > paper_numbers_final.md
"""

from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART = HERE.parent / "remote_artifacts"
RUNS = ART / "runs"
BASE = ["Adenovirus", "Astrovirus", "CCHF", "Cowpox", "Ebola", "Influenza", "Lassa", "Marburg", "Nipah virus",
        "Norovirus", "Orf", "Papilloma", "Rift Valley", "Rotavirus"]
NOVEL = ["Dengue", "Guanarito", "LCM", "Machupo", "Pseudocowpox", "Sapovirus", "TBE", "WestNile"]
S = ["E1_siamese_supcon_densenet201", "E1_siamese_supcon_densenet201_seed1", "E1_siamese_supcon_densenet201_seed2"]
P = ["E1_paper_densenet201", "E1_paper_densenet201_seed1", "E1_paper_densenet201_seed2"]
AUX, TRI, CE = "E6_supcon_auxce05_densenet201", "E6_triplet_densenet201", "E2_ce22_densenet201"
METHODS = [("ncm", "NCM"), ("logreg", "Logistic regression"), ("maha", "Shrunk Mahalanobis"),
           ("dc", "Distribution calibration")]
WEAK = ["Dengue", "Sapovirus", "Guanarito", "LCM", "Machupo"]


def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    return "\n".join(out + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def msd(v, scale=1.0, d=3):
    v = [scale * x for x in v]
    return f"{st.mean(v):.{d}f} ± {st.stdev(v):.{d}f}" if len(v) > 1 else f"{v[0]:.{d}f}"


def sig(ci):
    return ci[0] > 0 or ci[1] < 0


def rng(vals, scale=1.0, d=3, signed=True):
    f = (lambda x: f"{scale * x:+.{d}f}") if signed else (lambda x: f"{scale * x:.{d}f}")
    return f"{f(min(vals))} to {f(max(vals))}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    E = {r: load(RUNS / r / "eval_fp32" / "results.json") for r in S + P + [AUX, TRI, CE]}
    A = {r: load(RUNS / r / "analysis_fp32" / "analysis.json") for r in S + P + [AUX, TRI]}
    G = {r: load(RUNS / "gfsl_fp32" / r / "gfsl_improve.json")["checkpoints"] for r in S + P + [AUX]}
    G = {r: next(iter(v.values())) for r, v in G.items()}
    PG = load(RUNS / "paired_gfsl_final.json")
    PS = load(RUNS / "paired_seeds_fp32_local.json")
    T = {r: load(RUNS / r / "train_summary.json") for r in S + P + [AUX, TRI, CE]}
    D = load(ART / "report_data.json")
    C = load(HERE.parent / "tem_fewshot" / "temfs" / "expected_counts.json")["counts"]
    precisions = {r: E[r]["environment"]["inference_precision"] for r in E}
    precisions.update({f"gfsl:{r}": load(RUNS / "gfsl_fp32" / r / "gfsl_improve.json")["environment"]["inference_precision"]
                       for r in G})
    assert set(precisions.values()) == {"fp32-deterministic"}, precisions
    out = ["# Manuscript numbers v0.2 (auto-generated by extract_numbers_final.py; do not edit by hand)",
           "All test-set numbers: official test split, 8-view D4 TTA, fp32 deterministic inference "
           f"(checked for all {len(precisions)} result files).\n"]

    # ------------------------------------------------------------------ dataset
    rows = []
    for c in BASE + NOVEL:
        e = C[c]
        rows.append([c, "base" if c in BASE else "rare"] +
                    [f"{e[s]['patches']} ({e[s]['images']})" for s in ("train", "validation", "test")])
    out.append("## D1. Dataset: patches (micrographs)")
    out.append(table(["Class", "Role", "Train", "Validation", "Test"], rows))

    # ------------------------------------------------------------------ 14-class
    out.append("\n## T14. 14-class closed set")
    rows = []
    for r in S:
        for key in ("feat", "head"):
            c = E[r][key]["closed"]
            ci = c["bootstrap_ci95"]["accuracy"]
            rows.append([f"{r} ({key}, NCM)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}",
                         f"[{100 * ci['low']:.1f}, {100 * ci['high']:.1f}]", f"{100 * c['image_level']['accuracy']:.2f}"])
    for r in P:
        c = E[r]["logits"]["closed"]
        ci = c["bootstrap_ci95"]["accuracy"]
        rows.append([f"{r} (softmax)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}",
                     f"[{100 * ci['low']:.1f}, {100 * ci['high']:.1f}]", f"{100 * c['image_level']['accuracy']:.2f}"])
    for r in (AUX, TRI):
        c = E[r]["feat"]["closed"]
        rows.append([f"{r} (feat, NCM)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}", "",
                     f"{100 * c['image_level']['accuracy']:.2f}"])
    out.append(table(["Model", "Acc (%)", "Macro-F1", "Acc 95% CI", "Micrograph acc (%)"], rows))
    sa = [E[r]["feat"]["closed"]["accuracy"] for r in S]
    pa = [E[r]["logits"]["closed"]["accuracy"] for r in P]
    out.append(f"- Siamese feat, 3 seeds: acc {msd(sa, 100, 2)} %, macro-F1 {msd([E[r]['feat']['closed']['macro_f1'] for r in S])}, "
               f"micrograph acc {msd([E[r]['feat']['closed']['image_level']['accuracy'] for r in S], 100, 2)} %")
    out.append(f"- Siamese head, 3 seeds: acc {msd([E[r]['head']['closed']['accuracy'] for r in S], 100, 2)} %, "
               f"macro-F1 {msd([E[r]['head']['closed']['macro_f1'] for r in S])}")
    out.append(f"- B1 (paper model), 3 seeds: acc {msd(pa, 100, 2)} %, macro-F1 {msd([E[r]['logits']['closed']['macro_f1'] for r in P])}, "
               f"micrograph acc {msd([E[r]['logits']['closed']['image_level']['accuracy'] for r in P], 100, 2)} %")
    out.append(f"- Siamese minus B1 seed means: {100 * (st.mean(sa) - st.mean(pa)):+.2f} pts")
    k = [v for kk, v in PS.items() if kk.startswith("14class")]
    out.append(f"- 9 paired comparisons (Siamese feat vs B1 softmax, identical patches): acc diff "
               f"{rng([v['acc_diff'] for v in k], 100, 2)} pts; CI excludes 0 in {sum(sig(v['acc_diff_ci95']) for v in k)}/9; "
               f"macro-F1 diff {rng([v['macro_f1_diff'] for v in k])}; CI excludes 0 in "
               f"{sum(sig(v['macro_f1_diff_ci95']) for v in k)}/9; Siamese ahead in "
               f"{sum(v['acc_diff'] > 0 for v in k)}/9 (acc)")
    s0p0 = PS[f"14class_siamese_feat_vs_paper_logits|{S[0]}|{P[0]}"]
    out.append(f"- seed 0 vs seed 0: acc {100 * s0p0['acc_diff']:+.2f} [{100 * s0p0['acc_diff_ci95'][0]:+.2f}, "
               f"{100 * s0p0['acc_diff_ci95'][1]:+.2f}], macro-F1 {s0p0['macro_f1_diff']:+.3f} "
               f"[{s0p0['macro_f1_diff_ci95'][0]:+.3f}, {s0p0['macro_f1_diff_ci95'][1]:+.3f}], McNemar "
               f"{s0p0['mcnemar_a_right_b_wrong']}/{s0p0['mcnemar_a_wrong_b_right']} p={s0p0['mcnemar_p']:.3g}")
    hd = load(RUNS / "cmp_fp32_siamese_head_vs_paper.json")
    out.append(f"- head seed 0 vs B1 seed 0: acc {100 * hd['acc_diff']:+.2f} [{100 * hd['acc_diff_ci95'][0]:+.2f}, "
               f"{100 * hd['acc_diff_ci95'][1]:+.2f}], McNemar {hd['mcnemar_a_right_b_wrong']}/{hd['mcnemar_a_wrong_b_right']} "
               f"p={hd['mcnemar_p']:.3g}")

    # ------------------------------------------------------------------ 22-class NCM
    out.append("\n## T22. 22-class GFSL, nearest class mean (rare classes as prototypes)")
    rows = []
    for lab, runs, key in (("Siamese feat (3 seeds)", S, "feat"), ("Siamese head (3 seeds)", S, "head"),
                           ("B1 paper-model feat (3 seeds)", P, "feat")):
        g = [E[r][key]["gfsl"] for r in runs]
        rows.append([lab, msd([x["accuracy"] for x in g], 100, 2), msd([x["macro_f1"] for x in g]),
                     msd([x["gfsl_patch"]["base_acc"] for x in g], 100, 1),
                     msd([x["gfsl_patch"]["novel_mean_class_acc"] for x in g], 100, 1),
                     msd([x["image_level"]["accuracy"] for x in g], 100, 2)])
    for lab, r in (("SupCon + cosine CE (1 seed)", AUX), ("Triplet (1 seed)", TRI)):
        g = E[r]["feat"]["gfsl"]
        rows.append([lab, f"{100 * g['accuracy']:.2f}", f"{g['macro_f1']:.3f}", f"{100 * g['gfsl_patch']['base_acc']:.1f}",
                     f"{100 * g['gfsl_patch']['novel_mean_class_acc']:.1f}", f"{100 * g['image_level']['accuracy']:.2f}"])
    c = E[CE]["logits"]["closed"]
    rows.append(["B2: CE on all 22 classes (reference)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}",
                 f"{100 * c['gfsl_patch']['base_acc']:.1f}", f"{100 * c['gfsl_patch']['novel_mean_class_acc']:.1f}",
                 f"{100 * c['image_level']['accuracy']:.2f}"])
    out.append(table(["Model", "Acc (%)", "Macro-F1", "Base acc (%)", "Rare mean-class acc (%)", "Micrograph acc (%)"], rows))
    ci = c["bootstrap_ci95"]
    out.append(f"- B2 CI: acc [{100 * ci['accuracy']['low']:.1f}, {100 * ci['accuracy']['high']:.1f}], "
               f"macro-F1 [{ci['macro_f1']['low']:.3f}, {ci['macro_f1']['high']:.3f}]")
    k = [v for kk, v in PS.items() if kk.startswith("22class")]
    out.append(f"- 9 paired comparisons (Siamese vs B1 features, NCM): acc diff {rng([v['acc_diff'] for v in k], 100, 2)} pts, "
               f"CI excludes 0 in {sum(sig(v['acc_diff_ci95']) for v in k)}/9; macro-F1 diff {rng([v['macro_f1_diff'] for v in k])}, "
               f"CI excludes 0 in {sum(sig(v['macro_f1_diff_ci95']) for v in k)}/9")
    names = E[S[0]]["feat"]["gfsl"]["class_names"]
    i = names.index("Dengue")
    out.append("- Dengue test patches (44) predicted as Sapovirus with Siamese NCM: " +
               ", ".join(str(E[r]["feat"]["gfsl"]["confusion"][i][names.index("Sapovirus")]) for r in S))

    # ------------------------------------------------------------------ classifier study
    out.append("\n## G1. Classifiers on frozen backbone features, 22-class test (selection on validation macro-F1)")
    rows = []
    for lab, runs in (("Siamese", S), ("B1 paper-model", P)):
        for m, ml in METHODS:
            v = [G[r]["methods"][m] for r in runs]
            rows.append([lab, ml, msd([x["val_macro_f1"] for x in v]), msd([x["test"]["accuracy"] for x in v], 100, 2),
                         msd([x["test"]["macro_f1"] for x in v]), msd([x["test"]["base_acc"] for x in v], 100, 1),
                         msd([x["test"]["novel_mean_class_acc"] for x in v], 100, 1),
                         msd([x["kshot"]["1"]["novel_mean_class_acc"]["mean"] for x in v], 100, 1),
                         msd([x["kshot"]["5"]["novel_mean_class_acc"]["mean"] for x in v], 100, 1)])
    for m, ml in METHODS:
        x = G[AUX]["methods"][m]
        rows.append(["SupCon + cosine CE (1 seed)", ml, f"{x['val_macro_f1']:.3f}", f"{100 * x['test']['accuracy']:.2f}",
                     f"{x['test']['macro_f1']:.3f}", f"{100 * x['test']['base_acc']:.1f}",
                     f"{100 * x['test']['novel_mean_class_acc']:.1f}",
                     f"{100 * x['kshot']['1']['novel_mean_class_acc']['mean']:.1f}",
                     f"{100 * x['kshot']['5']['novel_mean_class_acc']['mean']:.1f}"])
    out.append(table(["Features", "Classifier", "Val macro-F1", "Test acc (%)", "Test macro-F1", "Base acc (%)",
                      "Rare mean-class (%)", "K=1 rare (%)", "K=5 rare (%)"], rows))
    out.append("\nSelected hyper-parameters and validation winner per checkpoint:")
    for r in S + P + [AUX]:
        win = max(METHODS, key=lambda mm: G[r]["methods"][mm[0]]["val_macro_f1"])[0]
        out.append(f"- {r}: winner={win}; " + "; ".join(f"{m}={G[r]['methods'][m]['selected_params']}" for m, _ in METHODS
                                                          if m != "ncm"))
    out.append("\nPer-run test macro-F1 (LR / Mahalanobis): " +
               "; ".join(f"{r}: {G[r]['methods']['logreg']['test']['macro_f1']:.3f} / {G[r]['methods']['maha']['test']['macro_f1']:.3f}"
                         f" (rare mean-class {100 * G[r]['methods']['maha']['test']['novel_mean_class_acc']:.1f})"
                         for r in S + P))

    out.append("\n## G2. Paired: classifier vs NCM on the same checkpoint (micrograph cluster bootstrap, 2000 resamples)")
    rows = []
    for r in S + P + [AUX]:
        row = [r]
        for m in ("logreg", "maha", "dc"):
            v = PG["within_checkpoint"].get(f"{r}|{m}_vs_ncm")
            if v is None:
                row.append("n/a")
                continue
            row.append(f"{v['macro_f1_diff']:+.3f} [{v['macro_f1_diff_ci95'][0]:+.3f}, {v['macro_f1_diff_ci95'][1]:+.3f}]"
                       f"{' *' if sig(v['macro_f1_diff_ci95']) else ''} / acc {100 * v['acc_diff']:+.2f}")
        rows.append(row)
    out.append(table(["Checkpoint", "LR - NCM: macro-F1 [CI] / acc pts", "Mahalanobis - NCM", "DC - NCM"], rows))

    out.append("\n## G3. Paired: Siamese vs B1 features with the same classifier (9 seed pairs)")
    rows = []
    for m, ml in METHODS:
        v = [PG["siamese_vs_baseline"][f"{s}|{b}|{m}"] for s in S for b in P]
        rows.append([ml, rng([x["macro_f1_diff"] for x in v]), f"{sum(sig(x['macro_f1_diff_ci95']) and x['macro_f1_diff'] > 0 for x in v)}"
                     f" / {sum(sig(x['macro_f1_diff_ci95']) and x['macro_f1_diff'] < 0 for x in v)}",
                     rng([x["acc_diff"] for x in v], 100, 2),
                     f"{sum(sig(x['acc_diff_ci95']) and x['acc_diff'] > 0 for x in v)} / "
                     f"{sum(sig(x['acc_diff_ci95']) and x['acc_diff'] < 0 for x in v)}"])
    out.append(table(["Classifier", "Macro-F1 diff range", "Sig. Siamese better / B1 better", "Acc diff range (pts)",
                      "Sig. Siamese better / B1 better"], rows))

    out.append("\n## G4. K-shot, rare mean-class accuracy (classifier study, 30 identical support draws)")
    rows = []
    for kk in ("1", "5"):
        for m, ml in METHODS:
            v = [PG["kshot"][f"K{kk}|{m}|{s}|{b}"] for s in S for b in P]
            rows.append([kk, ml, msd([G[s]["methods"][m]["kshot"][kk]["novel_mean_class_acc"]["mean"] for s in S], 100, 1),
                         msd([G[b]["methods"][m]["kshot"][kk]["novel_mean_class_acc"]["mean"] for b in P], 100, 1),
                         rng([x["diff"]["mean"] for x in v], 100, 1),
                         f"{sum(x['diff']['mean'] - x['diff']['ci95'] > 0 for x in v)} / "
                         f"{sum(x['diff']['mean'] + x['diff']['ci95'] < 0 for x in v)}"])
    out.append(table(["K", "Classifier", "Siamese (3 seeds)", "B1 (3 seeds)", "Paired diff range (pts)",
                      "Sig. Siamese better / B1 better (of 9)"], rows))
    for kk in ("1", "5"):
        d = [PG["kshot"][f"K{kk}|dc_vs_ncm|{r}"] for r in S + P]
        out.append(f"- K={kk} DC minus NCM, per checkpoint (S0,S1,S2,P0,P1,P2): " +
                   ", ".join(f"{100 * x['diff']['mean']:+.1f}{'*' if abs(x['diff']['mean']) > x['diff']['ci95'] else ''}" for x in d))

    out.append("\n## G5. Weak-class test F1 (mean over 3 seeds)")
    rows = []
    for lab, runs in (("Siamese", S), ("B1", P)):
        for m, ml in METHODS:
            rows.append([f"{lab}, {ml}"] + [f"{st.mean(G[r]['methods'][m]['test']['weak_f1'][c] for r in runs):.2f}" for c in WEAK])
    out.append(table(["Setting"] + WEAK, rows))
    sup = E[S[0]]["feat"]["gfsl"]["per_class"]["support"]
    out.append("Test patches: " + ", ".join(f"{c}={sup[names.index(c)]}" for c in WEAK))

    out.append("\n## G6. Pairwise separability on VALIDATION (binary LR trained on train): AUROC / LR acc / 2-class NCM acc")
    pairs = list(G[S[0]]["diagnostic_validation"].keys())
    rows = []
    for p in pairs:
        r = [p.replace("|", " vs ")]
        for lab, runs in (("S", S), ("P", P)):
            ds = [G[x]["diagnostic_validation"][p] for x in runs]
            r.append(f"{rng([d['auc_logreg'] for d in ds], signed=False)} / {rng([d['acc_logreg'] for d in ds], d=2, signed=False)} / "
                     f"{rng([d['acc_ncm'] for d in ds], d=2, signed=False)}")
        d = G[S[0]]["diagnostic_validation"][p]
        r.append(f"{d['n_val_a']}/{d['n_val_b']}")
        rows.append(r)
    out.append(table(["Pair", "Siamese (range over 3 seeds)", "B1 (range over 3 seeds)", "Val patches"], rows))

    # ------------------------------------------------------------------ K-shot curve (evaluate.py, 100 draws)
    out.append("\n## K1. K-shot curve, NCM, evaluate.py (100 draws): rare mean-class accuracy (%)")
    rows = []
    for kk in ("1", "3", "5", "10"):
        rows.append([kk, msd([E[r]["feat"]["kshot"][kk]["novel_mean_class_acc"]["mean"] for r in S], 100, 1),
                     msd([E[r]["feat"]["kshot"][kk]["novel_mean_class_acc"]["mean"] for r in P], 100, 1),
                     msd([E[r]["head"]["kshot"][kk]["novel_mean_class_acc"]["mean"] for r in S], 100, 1)])
    out.append(table(["K", "Siamese feat", "B1 feat", "Siamese head"], rows))

    # ------------------------------------------------------------------ open set, episodes
    out.append("\n## O1. Unknown-virus detection and 8-way rare-class episodes (feat)")
    rows = []
    for lab, runs in (("Siamese (3 seeds)", S), ("B1 (3 seeds)", P)):
        e = [E[r]["feat"] for r in runs]
        rows.append([lab, msd([x["openset"]["patch"]["auroc"] for x in e]),
                     msd([x["openset"]["patch"]["fpr_at_95tpr"] for x in e], 100, 1),
                     msd([x["openset"]["image"]["auroc"] for x in e]),
                     msd([x["episodic"]["1"]["acc"]["mean"] for x in e], 100, 1),
                     msd([x["episodic"]["5"]["acc"]["mean"] for x in e], 100, 1)])
    for lab, r in (("SupCon + cosine CE", AUX), ("Triplet", TRI)):
        x = E[r]["feat"]
        rows.append([lab, f"{x['openset']['patch']['auroc']:.3f}", f"{100 * x['openset']['patch']['fpr_at_95tpr']:.1f}",
                     f"{x['openset']['image']['auroc']:.3f}", f"{100 * x['episodic']['1']['acc']['mean']:.1f}",
                     f"{100 * x['episodic']['5']['acc']['mean']:.1f}"])
    out.append(table(["Model", "AUROC (patch)", "FPR@95TPR (%)", "AUROC (micrograph)", "8-way 1-shot (%)", "8-way 5-shot (%)"], rows))

    # ------------------------------------------------------------------ calibration variants
    out.append("\n## C1. Inference-time variants (analysis_fp32): 22-class macro-F1 raw -> calibrated (gamma from validation)")
    rows = []
    deltas = []
    for r in S + P + [AUX, TRI]:
        for var in ("feat_l2", "feat_cl2n"):
            x = A[r]["variants"][var]
            raw, cal = x["gfsl_test_raw"]["macro_f1"], x["gfsl_test_calibrated"]["macro_f1"]
            deltas.append(cal - raw)
            rows.append([r, var, f"{100 * x['closed_test']['accuracy']:.2f}", f"{raw:.3f}", f"{x['gamma_selected_on_val']:+.3f}",
                         f"{cal:.3f}"])
    out.append(table(["Run", "Variant", "14-class acc (%)", "22 macro-F1 raw", "gamma (val)", "22 macro-F1 calibrated"], rows))
    out.append(f"- calibrated minus raw macro-F1 over all rows: {rng(deltas)}")

    # ------------------------------------------------------------------ training
    out.append("\n## TR. Training runs (RTX 3060, AMP training)")
    rows = [[r, len(T[r]["history"]), T[r]["best_epoch"], T[r]["select_metric"], f"{T[r]['best_metric']:.4f}",
             f"{sum(h.get('train_time_s', 0) for h in T[r]['history']) / 60:.0f}"] for r in S + P + [AUX, TRI, CE]]
    out.append(table(["Run", "Epochs run", "Best epoch", "Selection metric", "Best val value", "Time (min)"], rows))

    # ------------------------------------------------------------------ pilots (unchanged, AMP)
    f1 = D["f1"]
    out.append("\n## F. Pilot experiments (round 1, AMP inference; not re-run)")
    out.append(f"- F1 frozen ImageNet DenseNet201, 14-class test: NCM {100 * f1['ncm_test']['accuracy']:.1f} %, "
               f"LR probe {100 * f1['linear_probe_test']['accuracy']:.1f} %")
    for tag in ("f2", "f3"):
        v = D[tag]["by_k"]["5"]
        d = v["paired_diff_trained_feat_vs_frozen"]
        out.append(f"- {tag.upper()} 4-way 5-shot unseen {D[tag]['hidden']}: frozen {100 * v['frozen_imagenet']['acc']['mean']:.1f}, "
                   f"trained feat {100 * v['trained_feat']['acc']['mean']:.1f}, head {100 * v['trained_head']['acc']['mean']:.1f}, "
                   f"paired {100 * d['mean']:+.1f} ± {100 * d['ci95']:.1f}")
    t, fz = D["f3_gfsl_trained"], D["f3_gfsl_frozen"]
