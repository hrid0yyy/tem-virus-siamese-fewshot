"""Collect every number quoted in the manuscript draft from the raw result files.

Inputs (downloaded from the training PC into ../remote_artifacts):
  report_data.json                 - collected by tem_fewshot/collect_results.py
  runs/gfsl_improve/gfsl_improve.json
  runs/*/eval_full/results.json    - K-shot (mean-class accuracy) for every checkpoint
and ../tem_fewshot/temfs/expected_counts.json for the dataset table.

    python extract_numbers.py > paper_numbers.md
"""

from __future__ import annotations

import json
import statistics as st
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ART = HERE.parent / "remote_artifacts"
BASE = ["Adenovirus", "Astrovirus", "CCHF", "Cowpox", "Ebola", "Influenza", "Lassa", "Marburg", "Nipah virus",
        "Norovirus", "Orf", "Papilloma", "Rift Valley", "Rotavirus"]
NOVEL = ["Dengue", "Guanarito", "LCM", "Machupo", "Pseudocowpox", "Sapovirus", "TBE", "WestNile"]
SEEDS = ["E1_siamese_supcon_densenet201", "E1_siamese_supcon_densenet201_seed1", "E1_siamese_supcon_densenet201_seed2"]
PAPER = "E1_paper_densenet201"
AUX = "E6_supcon_auxce05_densenet201"
TRIP = "E6_triplet_densenet201"
METHODS = [("ncm", "Nearest class mean (cosine)"), ("maha", "Shrunk Mahalanobis (Simple-CNAPS style)"),
           ("logreg", "Logistic regression"), ("dc", "Distribution calibration")]


def load(p):
    with open(p, encoding="utf-8") as f:
        return json.load(f)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def msd(v, scale=1.0, d=3):
    v = [scale * x for x in v]
    return f"{st.mean(v):.{d}f} ± {st.stdev(v):.{d}f}" if len(v) > 1 else f"{v[0]:.{d}f}"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    D = load(ART / "report_data.json")
    G = load(ART / "runs" / "gfsl_improve" / "gfsl_improve.json")["checkpoints"]
    G = {k.replace("\\", "/").split("/")[1]: v for k, v in G.items()}
    C = load(HERE.parent / "tem_fewshot" / "temfs" / "expected_counts.json")["counts"]
    out = ["# Numbers used in the manuscript (auto-generated by extract_numbers.py; do not edit by hand)\n"]

    # ------------------------------------------------------------------ dataset
    rows, tot = [], {"tp": 0, "vp": 0, "sp": 0, "ti": 0, "vi": 0, "si": 0, "ex": 0, "exi": 0}
    for c in BASE + NOVEL:
        e = C[c]
        if c in BASE:
            r = [c, "base", e["train"]["patches"], e["train"]["images"], e["validation"]["patches"],
                 e["validation"]["images"], e["test"]["patches"], e["test"]["images"]]
            tot["tp"] += e["train"]["patches"]; tot["ti"] += e["train"]["images"]
            tot["vp"] += e["validation"]["patches"]; tot["vi"] += e["validation"]["images"]
            tot["sp"] += e["test"]["patches"]; tot["si"] += e["test"]["images"]
        else:
            r = [c, "rare"]
            for s in ("train", "validation", "test"):
                r += [e[s]["patches"], e[s]["images"]] if s in e else ["-", "-"]
        rows.append(r)
    out.append("## D1. Dataset (official patch folders, 256x256 px at 1 nm/px)")
    out.append(table(["Class", "Role", "Train patches", "Train micrographs", "Val patches", "Val micrographs",
                      "Test patches", "Test micrographs"], rows))
    out.append(f"\nRaw count keys available per class: {sorted(C['Dengue'].keys())}")

    # ------------------------------------------------------------------ gfsl study
    out.append("\n## G1. Rare-class study: 22-class GFSL on the official TEST split, frozen backbone features "
               "(hyper-parameters selected on VALIDATION macro-F1)")
    rows = []
    for name in SEEDS + [AUX, PAPER]:
        for m, lab in METHODS:
            r = G[name]["methods"][m]
            t = r["test"]
            ci = t["ci95"]["macro_f1"]
            rows.append([name, lab, r["selected_params"], f"{r['val_macro_f1']:.3f}", f"{100 * t['accuracy']:.2f}",
                         f"{t['macro_f1']:.3f} [{ci['low']:.3f}, {ci['high']:.3f}]", f"{100 * t['base_acc']:.1f}",
                         f"{100 * t['novel_mean_class_acc']:.1f}", f"{t['hm_mean_class_acc']:.3f}"])
    out.append(table(["Checkpoint", "Classifier", "Selected (val)", "Val macro-F1", "Test acc (%)",
                      "Test macro-F1 [95% CI]", "Base acc (%)", "Rare mean-class acc (%)", "HM (mean-class)"], rows))

    # winner on validation per checkpoint
    out.append("\nValidation winner per checkpoint (pre-declared rule: pick the classifier with the highest "
               "validation macro-F1):")
    for name in SEEDS + [AUX, PAPER]:
        best = max(METHODS, key=lambda m: G[name]["methods"][m[0]]["val_macro_f1"])
        out.append(f"- {name}: {best[0]} (val macro-F1 {G[name]['methods'][best[0]]['val_macro_f1']:.3f})")

    out.append("\n## G2. Siamese (SupCon), mean ± SD over 3 training seeds, 22-class test")
    rows = []
    for m, lab in METHODS:
        get = lambda f: [f(G[s]["methods"][m]) for s in SEEDS]
        rows.append([lab,
                     msd(get(lambda r: r["val_macro_f1"])),
                     msd(get(lambda r: r["test"]["accuracy"]), 100, 2),
                     msd(get(lambda r: r["test"]["macro_f1"])),
                     msd(get(lambda r: r["test"]["base_acc"]), 100, 1),
                     msd(get(lambda r: r["test"]["novel_mean_class_acc"]), 100, 1),
                     msd(get(lambda r: r["kshot"]["1"]["novel_mean_class_acc"]["mean"]), 100, 1),
                     msd(get(lambda r: r["kshot"]["5"]["novel_mean_class_acc"]["mean"]), 100, 1)])
    out.append(table(["Classifier", "Val macro-F1", "Test acc (%)", "Test macro-F1", "Base acc (%)",
                      "Rare mean-class acc (%)", "K=1 rare mean-class (%)", "K=5 rare mean-class (%)"], rows))
    out.append("\nSame quantities for single-seed checkpoints:")
    rows = []
    for name in (AUX, PAPER):
        for m, lab in METHODS:
            r = G[name]["methods"][m]
            rows.append([name, lab, f"{r['test']['macro_f1']:.3f}", f"{100 * r['test']['novel_mean_class_acc']:.1f}",
                         f"{100 * r['kshot']['1']['novel_mean_class_acc']['mean']:.1f} ± "
                         f"{100 * r['kshot']['1']['novel_mean_class_acc']['ci95']:.1f}",
                         f"{100 * r['kshot']['5']['novel_mean_class_acc']['mean']:.1f} ± "
                         f"{100 * r['kshot']['5']['novel_mean_class_acc']['ci95']:.1f}"])
    out.append(table(["Checkpoint", "Classifier", "Test macro-F1", "Rare mean-class acc (%)",
                      "K=1 (mean ± 95% CI half-width, 10 draws)", "K=5"], rows))

    out.append("\n## G3. Per-class test F1 of the weak classes")
    weak = list(G[SEEDS[0]]["methods"]["ncm"]["test"]["weak_f1"].keys())
    rows = []
    for m, lab in METHODS:
        rows.append([f"Siamese 3-seed mean, {lab}"] +
                    [f"{st.mean(G[s]['methods'][m]['test']['weak_f1'][c] for s in SEEDS):.2f}" for c in weak])
    for m, lab in METHODS:
        rows.append([f"Paper-model features, {lab}"] +
                    [f"{G[PAPER]['methods'][m]['test']['weak_f1'][c]:.2f}" for c in weak])
    out.append(table(["Setting"] + weak, rows))
    names = BASE + NOVEL
    sup = D["runs"][SEEDS[0]]["eval"]["feat"]["gfsl"]["per_class"]["support"]
    gnames = D["runs"][SEEDS[0]]["eval"]["feat"]["gfsl"]["class_names"]
    out.append("\nTest patches: " + ", ".join(f"{c}={sup[gnames.index(c)]}" for c in weak))

    out.append("\n## G4. Pairwise separability on VALIDATION (binary logistic regression trained on TRAIN patches)")
    pairs = list(G[SEEDS[0]]["diagnostic_validation"].keys())
    rows = []
    for p in pairs:
        r = [p.replace("|", " vs ")]
        for name in SEEDS + [PAPER]:
            d = G[name]["diagnostic_validation"][p]
            r.append(f"{d['auc_logreg']:.3f} / {d['acc_logreg']:.2f} / {d['acc_ncm']:.2f}")
        d = G[SEEDS[0]]["diagnostic_validation"][p]
        r.append(f"{d['n_val_a']}/{d['n_val_b']}")
        rows.append(r)
    out.append(table(["Pair", "Siamese s0: AUC / LR acc / NCM acc", "Siamese s1", "Siamese s2", "Paper-model feat",
                      "Val patches (a/b)"], rows))

    # ------------------------------------------------------------------ K-shot from evaluate.py (100 draws)
    out.append("\n## K1. K-shot curve from evaluate.py (NCM, 100 draws): rare mean-class accuracy and micro accuracy")
    rows = []
    for k in ("1", "3", "5", "10"):
        r = [k]
        sv = [D["runs"][s]["eval"]["feat"]["kshot"][k] for s in SEEDS]
        r.append(msd([x["novel_mean_class_acc"]["mean"] for x in sv], 100, 1))
        r.append(msd([x["novel_acc"]["mean"] for x in sv], 100, 1))
        p = D["runs"][PAPER]["eval"]["feat"]["kshot"][k]
        r.append(f"{100 * p['novel_mean_class_acc']['mean']:.1f}")
        r.append(f"{100 * p['novel_acc']['mean']:.1f}")
        rows.append(r)
    out.append(table(["K", "Siamese feat mean-class (3 seeds)", "Siamese feat micro (3 seeds)",
                      "Paper feat mean-class", "Paper feat micro"], rows))

    # ------------------------------------------------------------------ open set / episodic, seeds
    out.append("\n## O1. Unknown-virus detection and 8-way episodes on the rare classes (backbone feat)")
    rows = []
    for name in SEEDS + [AUX, TRIP, PAPER]:
        e = D["runs"][name]["eval"]["feat"]
        rows.append([name, f"{e['openset']['patch']['auroc']:.3f}", f"{100 * e['openset']['patch']['fpr_at_95tpr']:.1f}",
                     f"{e['openset']['image']['auroc']:.3f}", f"{100 * e['episodic']['1']['acc']['mean']:.1f}",
                     f"{100 * e['episodic']['5']['acc']['mean']:.1f}"])
    out.append(table(["Checkpoint", "AUROC patch", "FPR@95TPR (%)", "AUROC micrograph", "8-way 1-shot (%)",
                      "8-way 5-shot (%)"], rows))
    a = [D["runs"][s]["eval"]["feat"]["openset"]["patch"]["auroc"] for s in SEEDS]
    e1 = [D["runs"][s]["eval"]["feat"]["episodic"]["1"]["acc"]["mean"] for s in SEEDS]
    e5 = [D["runs"][s]["eval"]["feat"]["episodic"]["5"]["acc"]["mean"] for s in SEEDS]
    out.append(f"- Siamese 3 seeds: AUROC {msd(a)}, 8-way 1-shot {msd(e1, 100, 1)} %, 5-shot {msd(e5, 100, 1)} %")

    # ------------------------------------------------------------------ 22-class closest-average seeds + image level
    out.append("\n## E2b. 22-class GFSL with nearest class mean, micrograph-level and 14-class-only numbers")
    rows = []
    for name in SEEDS + [AUX, TRIP, PAPER]:
        g = D["runs"][name]["eval"]["feat"]["gfsl"]
        rows.append([name, f"{100 * g['accuracy']:.2f}", f"{g['macro_f1']:.3f}",
                     f"{100 * g['image_level']['accuracy']:.2f}", f"{g['image_level']['macro_f1']:.3f}",
                     f"{100 * g['gfsl_patch']['base_acc']:.1f}", f"{100 * g['gfsl_patch']['novel_acc']:.1f}",
                     f"{100 * g['gfsl_patch']['novel_mean_class_acc']:.1f}"])
    ce = D["runs"]["E2_ce22_densenet201"]["eval"]["logits"]["closed"]
    rows.append(["E2_ce22 (logits, rare classes trained)", f"{100 * ce['accuracy']:.2f}", f"{ce['macro_f1']:.3f}",
                 f"{100 * ce['image_level']['accuracy']:.2f}", f"{ce['image_level']['macro_f1']:.3f}",
                 f"{100 * ce['gfsl_patch']['base_acc']:.1f}", f"{100 * ce['gfsl_patch']['novel_acc']:.1f}",
                 f"{100 * ce['gfsl_patch']['novel_mean_class_acc']:.1f}"])
    out.append(table(["Checkpoint", "Patch acc (%)", "Patch macro-F1", "Micrograph acc (%)", "Micrograph macro-F1",
                      "Base acc (%)", "Rare micro acc (%)", "Rare mean-class acc (%)"], rows))

    out.append("\n## E1b. 14-class closed set, micrograph level and macro precision/recall (eval.py, TTA)")
    rows = []
    for name in SEEDS + [AUX, TRIP]:
        c = D["runs"][name]["eval"]["feat"]["closed"]
        rows.append([name + " (feat)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}",
                     f"{c['macro_precision']:.3f}", f"{c['macro_recall']:.3f}", f"{100 * c['image_level']['accuracy']:.2f}"])
    c = D["runs"][PAPER]["eval"]["logits"]["closed"]
    rows.append([PAPER + " (logits)", f"{100 * c['accuracy']:.2f}", f"{c['macro_f1']:.3f}", f"{c['macro_precision']:.3f}",
                 f"{c['macro_recall']:.3f}", f"{100 * c['image_level']['accuracy']:.2f}"])
    out.append(table(["Model", "Acc (%)", "Macro-F1", "Macro-P", "Macro-R", "Micrograph acc (%)"], rows))
    print("\n".join(out))


if __name__ == "__main__":
    main()
